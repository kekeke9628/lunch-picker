# 업종만으로는 잡히지 않는 가격대. 상호에 이 말이 있으면 기준가를 갈아끼운다.
NAME_OVERRIDE = [("오마카세", 35000), ("구내식당", 7000)]


def haversine(a_lat, a_lng, b_lat, b_lng):
    R = 6371000.0
    p1, p2 = math.radians(a_lat), math.radians(b_lat)
    dp, dl = math.radians(b_lat - a_lat), math.radians(b_lng - a_lng)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * R * math.asin(math.sqrt(h))


def nearest_district(lat, lng):
    return min(DISTRICTS, key=lambda d: haversine(lat, lng, d[1], d[2]))


def estimate(name, naver_cat, lat, lng, fallback):
    base = BASE.get(naver_cat, fallback)
    for needle, override in NAME_OVERRIDE:
        if needle in name:
            base = override
            break
    district = nearest_district(lat, lng)
    price = base * district[3] / SEOUL_AVG
    return int(round(price / 500.0) * 500), district[0]
